import Foundation

public enum ProgressKind: Sendable, Equatable {
    /// ffmpeg run with `-progress pipe:1`; fraction = out_time / total.
    case ffmpeg(totalSeconds: Double)
    /// mkvmerge/mkvextract run with `--gui-mode`.
    case mkvtoolnix
    /// MP4Box's "(n/100)" progress bars.
    case mp4box
    case indeterminate
}

public struct JobStep: Sendable, Equatable {
    public var label: String
    public var tool: Tool
    public var executable: URL
    public var arguments: [String]
    public var progress: ProgressKind
    public var workingDirectory: URL?

    public init(label: String, tool: Tool, executable: URL, arguments: [String], progress: ProgressKind, workingDirectory: URL? = nil) {
        self.label = label
        self.tool = tool
        self.executable = executable
        self.arguments = arguments
        self.progress = progress
        self.workingDirectory = workingDirectory
    }

    public var commandLine: String { shellQuoted([executable.path] + arguments) }
}

public struct JobPlan: Sendable {
    public var title: String
    public var steps: [JobStep]
    /// Expected output files. Removed if the job fails or is cancelled.
    public var outputs: [URL]
    /// Folder that receives outputs (for "Show in Finder" when names are generated by the tool).
    public var outputFolder: URL
    /// Temporary files to delete when the job ends.
    public var temporaryFiles: [URL]
    public var warnings: [String]

    public init(title: String, steps: [JobStep], outputs: [URL], outputFolder: URL, temporaryFiles: [URL] = [], warnings: [String] = []) {
        self.title = title
        self.steps = steps
        self.outputs = outputs
        self.outputFolder = outputFolder
        self.temporaryFiles = temporaryFiles
        self.warnings = warnings
    }
}

/// Parses progress from a line of tool output. Returns a 0...1 fraction, or nil if the line isn't progress.
public enum ProgressParser {
    public static func fraction(from line: Substring, kind: ProgressKind) -> Double? {
        switch kind {
        case .ffmpeg(let total):
            if line.hasPrefix("progress=end") { return 1 }
            guard total > 0, line.hasPrefix("out_time_us=") || line.hasPrefix("out_time_ms=") else { return nil }
            guard let micros = Double(line.split(separator: "=", maxSplits: 1).last ?? "") else { return nil }
            return min(1, max(0, micros / 1_000_000 / total))
        case .mkvtoolnix:
            guard let range = line.range(of: "#GUI#progress ") else { return nil }
            let number = line[range.upperBound...].prefix { $0.isNumber }
            return Double(number).map { $0 / 100 }
        case .mp4box:
            // Either "Importing: |====    | (45/100)" or "splitting:  12.34 %".
            if let close = line.range(of: "/100)", options: .backwards),
               let open = line[..<close.lowerBound].lastIndex(of: "(") {
                return Double(line[line.index(after: open)..<close.lowerBound]).map { $0 / 100 }
            }
            if let pct = line.range(of: " %", options: .backwards) {
                let number = line[..<pct.lowerBound].reversed().prefix { $0.isNumber || $0 == "." }
                return Double(String(number.reversed())).map { min(1, $0 / 100) }
            }
            return nil
        case .indeterminate:
            return nil
        }
    }
}

/// Picks "Name.ext", then "Name 2.ext", and so on, skipping files that exist or are already planned.
public func uniqueURL(in folder: URL, baseName: String, extension ext: String, reserved: Set<URL> = []) -> URL {
    let fm = FileManager.default
    var n = 1
    while true {
        let name = n == 1 ? baseName : "\(baseName) \(n)"
        let url = folder.appendingPathComponent(name).appendingPathExtension(ext)
        if !fm.fileExists(atPath: url.path), !reserved.contains(url) { return url }
        n += 1
    }
}
